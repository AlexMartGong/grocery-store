package com.amx.grocerystore.users;

import org.junit.jupiter.api.Test;
import org.springframework.security.crypto.bcrypt.BCryptPasswordEncoder;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

class SeedTestUsersTest {

    private record SeedUser(String id, String fullName, String username, String password, String role) {
    }

    @Test
    void generateSeedScript() throws IOException {
        BCryptPasswordEncoder encoder = new BCryptPasswordEncoder();

        String storeId = "00000000-0000-0000-0000-000000000001";
        String storeCode = "tienda-demo";
        List<SeedUser> users = List.of(
                new SeedUser("10000000-0000-0000-0000-000000000001", "Tienda Demo Owner", "owner", "owner123", "OWNER"),
                new SeedUser("10000000-0000-0000-0000-000000000002", "Cajera Uno", "cashier1", "cashier1", "CASHIER"),
                new SeedUser("10000000-0000-0000-0000-000000000003", "Cajero Dos", "cashier2", "cashier2", "CASHIER")
        );

        StringBuilder sql = new StringBuilder();
        sql.append("-- Generated by SeedTestUsersTest. Run against an empty (or matching) DB.\n");
        sql.append("-- Store code: ").append(storeCode).append(" (id: ").append(storeId).append(")\n");
        sql.append("-- Credentials (plaintext): ");
        users.forEach(u -> sql.append(u.username()).append('/').append(u.password()).append("  "));
        sql.append("\n\n");

        sql.append("INSERT INTO stores (id, code, name, owner_name, whatsapp, address, status)\n")
                .append("VALUES ('").append(storeId).append("', '").append(storeCode)
                .append("', 'Tienda Demo', 'Owner Demo', '3330000000', 'Calle Falsa 123, Tequila', 'ACTIVE')\n")
                .append("ON CONFLICT (id) DO UPDATE SET code = EXCLUDED.code;\n\n");

        for (SeedUser u : users) {
            String hash = encoder.encode(u.password());
            sql.append("INSERT INTO users (id, store_id, full_name, username, password_hash, role, active)\n")
                    .append("VALUES ('").append(u.id()).append("', '").append(storeId)
                    .append("', '").append(u.fullName().replace("'", "''"))
                    .append("', '").append(u.username())
                    .append("', '").append(hash)
                    .append("', '").append(u.role())
                    .append("', TRUE)\n")
                    .append("ON CONFLICT (id) DO UPDATE SET password_hash = EXCLUDED.password_hash;\n\n");
        }

        Path out = Path.of("target", "seed", "test-users.sql");
        Files.createDirectories(out.getParent());
        Files.writeString(out, sql.toString());

        System.out.println("=== SEED SQL (" + out.toAbsolutePath() + ") ===");
        System.out.println(sql);
        System.out.println("=== END SEED SQL ===");
    }
}
