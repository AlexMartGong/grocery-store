package com.amx.grocerystore.admin;

import org.junit.jupiter.api.Test;
import org.springframework.security.crypto.bcrypt.BCryptPasswordEncoder;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

class SeedTestAdminUsersTest {

    private record SeedAdmin(String id, String fullName, String username, String password) {
    }

    @Test
    void generateSeedScript() throws IOException {
        BCryptPasswordEncoder encoder = new BCryptPasswordEncoder();

        List<SeedAdmin> admins = List.of(
                new SeedAdmin("20000000-0000-0000-0000-000000000001", "Alex Martinez", "alex", "alex123"),
                new SeedAdmin("20000000-0000-0000-0000-000000000002", "Admin Prueba", "admin", "admin123")
        );

        StringBuilder sql = new StringBuilder();
        sql.append("-- Generated by SeedTestAdminUsersTest. Run against an empty (or matching) DB.\n");
        sql.append("-- Credentials (plaintext): ");
        admins.forEach(a -> sql.append(a.username()).append('/').append(a.password()).append("  "));
        sql.append("\n\n");

        for (SeedAdmin a : admins) {
            String hash = encoder.encode(a.password());
            sql.append("INSERT INTO admin_users (id, username, password_hash, full_name, role, active)\n")
                    .append("VALUES ('").append(a.id()).append("', '").append(a.username())
                    .append("', '").append(hash)
                    .append("', '").append(a.fullName().replace("'", "''"))
                    .append("', 'SUPER_ADMIN', TRUE)\n")
                    .append("ON CONFLICT (id) DO UPDATE SET password_hash = EXCLUDED.password_hash;\n\n");
        }

        Path out = Path.of("target", "seed", "test-admin-users.sql");
        Files.createDirectories(out.getParent());
        Files.writeString(out, sql.toString());

        System.out.println("=== SEED SQL (" + out.toAbsolutePath() + ") ===");
        System.out.println(sql);
        System.out.println("=== END SEED SQL ===");
    }
}
